#!/usr/bin/env node
/**
 * Converts the server-built liveness bundle into a React Native JS module.
 * Inlines all CSS + JS into a single HTML string exported as a JS module.
 * Usage: node scripts/build-rn.js
 */
const fs = require('fs');
const path = require('path');

const distDir  = path.resolve(__dirname, '../../backend/public/liveness');
const outFile  = path.resolve(__dirname, '../../sakhi-customer/src/liveness/livenessHtml.js');

let html = fs.readFileSync(path.join(distDir, 'index.html'), 'utf-8');

// ── Inline CSS ─────────────────────────────────────────────────────────────
html = html.replace(
  /<link\s+rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/g,
  (_match, href) => {
    const file = path.join(distDir, href.replace('/liveness/', ''));
    const css  = fs.readFileSync(file, 'utf-8');
    return `<style>${css}</style>`;
  },
);

// ── Inline JS (drop type=module + crossorigin for WebView compat) ──────────
html = html.replace(
  /<script[^>]*src="([^"]+)"[^>]*><\/script>/g,
  (_match, src) => {
    const file = path.join(distDir, src.replace('/liveness/', ''));
    const js   = fs.readFileSync(file, 'utf-8');
    return `<script>${js}</script>`;
  },
);

// ── Ensure dark background is in the inline style block ───────────────────
html = html.replace(
  '</head>',
  `<style>html,body,#root{margin:0;padding:0;width:100%;height:100%;background:#000;overflow:hidden;}</style>\n</head>`,
);

// ── Write JS module ────────────────────────────────────────────────────────
const output = [
  '// Auto-generated by liveness-web/scripts/build-rn.js — do not edit manually.',
  '// Run: cd liveness-web && npm run build:rn',
  `export default ${JSON.stringify(html)};`,
  '',
].join('\n');

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, output, 'utf-8');

const htmlKb   = (html.length   / 1024).toFixed(0);
const moduleKb = (output.length / 1024).toFixed(0);
console.log(`✓ livenessHtml.js written — HTML: ${htmlKb} KB, module: ${moduleKb} KB`);
console.log(`  → ${outFile}`);
